# ──────────────────────────────────────────────────────────────
# ② RAG 策略判断（分类节点：LLM 二次确认后选择检索策略）
# ──────────────────────────────────────────────────────────────

RAG_STRATEGY_PROMPT = """判断以下学员问题应采用哪种检索策略。

【策略定义】
PRECISE：问题表达明确，含具体技术点，可直接向量检索。
         例："Redis ZSet 的底层数据结构是什么" / "项目里 LSTM 那层怎么定义的"

VAGUE  ：问题模糊，只给出宽泛意图，直接检索效果差，需先生成假设文档扩充语义再检索（HyDE）。
         例："解释一下" / "我没太懂这块" / "能说说吗"

BROAD  ：问题范围过宽或极度简短（≤5字），需拆成多个子问题并行检索扩大召回（Multi-Query）。
         例："没懂" / "讲讲微服务" / "项目怎么做"

ITERATIVE：问题包含 2-3 个前后依赖的信息需求，后一个问题必须先知道前一个问题检索得到的实体或事实，
           才能构造有效检索 Query，需要逐轮检索并根据中间证据继续查询。
           例："EduRAG 使用哪些数据库？它们分别负责什么？"
           例："这个项目用了哪些模型？这些模型分别在哪个模块使用？各模块如何协作？"

注意：多个彼此独立、在检索前就能完整拆出的子问题属于 BROAD；只有存在前后依赖时才是 ITERATIVE。

【学员问题】
{query}

只输出一个词：PRECISE、VAGUE、BROAD、ITERATIVE"""


