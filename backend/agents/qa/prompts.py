# ──────────────────────────────────────────────────────────────
# ⑤ Iterative Retrieval：依赖规划 / 依赖 Query 展开 / 证据充分性
# ──────────────────────────────────────────────────────────────

ITERATIVE_PLAN_PROMPT = """你是 RAG Iterative Retrieval Planner。
请把用户问题拆成最多 3 个“逻辑问题”，并标出依赖关系。

规则：
1. 只保留用户原问题中实际存在的信息需求，不额外扩展。
2. 第一个问题通常是 seed，用于发现后续问题需要的实体或事实。
3. depends_on 只能引用前面已经出现的问题 id。
4. 如果后两个问题都只依赖 seed，则它们都 depends_on=["q1"]，后续可以并行。
5. 如果 q3 必须依赖 q2 的结果，则 q3 depends_on 至少包含 "q2"。
6. query 写成这一阶段应检索的目标；不能假设尚未检索得到的实体名称。
7. 最多输出 3 个问题，超过的忽略。

用户问题：
{query}

只输出 JSON，不要 Markdown：
{{
  "questions": [
    {{"id":"q1","query":"...","intent":"...","depends_on":[]}},
    {{"id":"q2","query":"...","intent":"...","depends_on":["q1"]}}
  ]
}}"""


ITERATIVE_EXPAND_PROMPT = """你是 RAG 依赖查询生成器。
当前逻辑问题依赖前一阶段检索证据。请只根据证据，把它展开成可以直接检索的具体 Query。

当前问题：{query}
当前意图：{intent}

依赖证据：
{evidence}

要求：
1. 不得凭空补充证据里不存在的实体。
2. 如果证据中发现多个相关实体，可为每个实体分别生成 Query。
3. 最多 3 个 Query。
4. entities 只填写本轮从证据中实际用于展开 Query 的实体；没有则为空数组。

只输出 JSON，不要 Markdown：
{{"entities":["..."],"queries":["..."]}}"""


ITERATIVE_SUFFICIENCY_PROMPT = """判断当前检索证据是否足以回答用户原问题的主要信息需求。

用户问题：
{query}

逻辑问题：
{plan}

已检索证据：
{evidence}

如果主要问题都有直接或可合理归纳的证据，输出 SUFFICIENT；
如果仍缺少关键子问题证据，输出 INSUFFICIENT。
只输出一个词。"""


