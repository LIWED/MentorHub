RAG_STRATEGY_PROMPT = """判断以下学员问题的检索结构。

【策略定义】
SINGLE：单一、明确的信息需求，不需要拆成多个独立子问题。
        即使答案包含多个实体，只要这些实体属于同一个信息需求，也仍然是 SINGLE。
        例："项目里用了哪些数据库？" / "Redis ZSet 的底层数据结构是什么？"

BROAD：问题同时包含多个彼此独立的角度，检索前就可以完整拆成多个子问题，
       适合 Multi-Query 并行检索。
       例："介绍一下项目的整体架构、检索方案和记忆机制。"
       例："对比 Redis 和 MySQL 的用途、优缺点和适用场景。"

ITERATIVE：问题包含 2-3 个前后依赖的信息需求，后一个问题必须先知道前一个问题检索得到的实体或事实，
          才能构造有效检索 Query，需要逐轮检索并根据中间证据继续查询。
          例："EduRAG 使用哪些数据库？它们分别负责什么？"
          例："这个项目用了哪些模型？这些模型分别在哪个模块使用？各模块如何协作？"

注意：
1. "有哪些/哪些" 不等于 BROAD；如果只是询问同一类实体列表，属于 SINGLE。
2. 多个彼此独立、检索前就能完整拆出的子问题属于 BROAD。
3. 只有后续 Query 依赖前一轮检索结果时才属于 ITERATIVE。
4. HyDE 不属于这里的结构分类；它由检索质量决定是否作为二次检索增强。

【学员问题】
{query}

只输出一个词：SINGLE、BROAD、ITERATIVE"""


